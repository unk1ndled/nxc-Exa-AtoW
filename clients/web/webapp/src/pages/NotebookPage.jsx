function Cell({ cell, index, isActive, onActivate, onChange, onRun }) {
  const state = cell.running
    ? "running"
    : cell.outputs.some((o) => o.type === "error")
      ? "error"
      : cell.outputs.length
        ? "ok"
        : "idle";

  return (
    <div
      className={`group relative border rounded-sm transition-colors ${
        isActive ? "border-accent1" : "border-rule hover:border-muted"
      }`}
      onClick={onActivate}
    >
      {/* Header */}
      <div className="flex items-center justify-between px-3 py-1.5 border-b border-rule bg-paper-alt">
        <div className="flex items-center gap-2">
          <span className="text-[10px] text-muted tracking-widest uppercase">
            {cell.type === "code" ? "code" : "text"}
          </span>
          <span className="text-[10px] text-muted opacity-40">[ {index} ]</span>
        </div>
        {cell.type === "code" && (
          <button
            onClick={(e) => {
              e.stopPropagation();
              onRun(cell.id);
            }}
            disabled={cell.running}
            className="flex items-center gap-1.5 text-[10px] tracking-wider text-muted hover:text-accent1 disabled:opacity-40 disabled:cursor-not-allowed transition-colors px-2 py-0.5 rounded-sm border border-transparent hover:border-accent1"
          >
            {cell.running ? (
              <span className="animate-pulse">◌ running</span>
            ) : (
              <>
                <span>▶</span> run
              </>
            )}
          </button>
        )}
      </div>

      {/* Body */}
      <div className="px-4 py-3">
        {cell.type === "markdown" ? (
          <MarkdownRenderer content={cell.content} />
        ) : (
          <CodeMirror
            value={cell.content}
            extensions={[python(), editorTheme]}
            onChange={(val) => onChange(cell.id, val)}
            basicSetup={{
              lineNumbers: false,
              foldGutter: false,
              highlightActiveLine: false,
              highlightActiveLineGutter: false,
              indentOnInput: true,
              tabSize: 4,
            }}
          />
        )}
      </div>

      <CellOutput outputs={cell.outputs} state={state} />
    </div>
  );
}

// ---------------------------------------------------------------------------
// Page
// ---------------------------------------------------------------------------

export default function NotebookPage() {
  const [cells, setCells] = useState(INITIAL_CELLS);
  const [activeCell, setActiveCell] = useState(null);
  const [showExplorer, setShowExplorer] = useState(false);

  const {
    sessionId,
    sessionIdRef,
    sessionStatus,
    sessionError,
    startSession,
    stopSession,
  } = useNotebookSession("atow_client_id");

  // -- Cell actions ---------------------------------------------------------

  const handleChange = useCallback((id, value) => {
    setCells((prev) =>
      prev.map((c) => (c.id === id ? { ...c, content: value } : c)),
    );
  }, []);

  const runCell = useCallback(
    async (id) => {
      if (sessionStatus !== "ready") return;
      const cell = cells.find((c) => c.id === id);
      if (!cell || cell.type !== "code") return;

      setCells((prev) =>
        prev.map((c) =>
          c.id === id ? { ...c, running: true, outputs: [] } : c,
        ),
      );

      try {
        const res = await authFetch(
          `${API_URL}/sessions/${sessionIdRef.current}/execute`,
          {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({ code: cell.content }),
          },
        );
        const data = await res.json();
        const outputs = res.ok
          ? data.outputs
          : [{ type: "error", text: data.detail }];
        setCells((prev) =>
          prev.map((c) =>
            c.id === id ? { ...c, running: false, outputs } : c,
          ),
        );
      } catch (e) {
        setCells((prev) =>
          prev.map((c) =>
            c.id === id
              ? { ...c, running: false, outputs: [{ type: "error", text: e.message }] }
              : c,
          ),
        );
      }
    },
    [cells, sessionStatus, sessionIdRef],
  );

  const runAll = useCallback(async () => {
    for (const cell of cells) {
      if (cell.type === "code") await runCell(cell.id);
    }
  }, [cells, runCell]);

  const restart = useCallback(async () => {
    if (!sessionIdRef.current || sessionStatus !== "ready") return;
    await authFetch(`${API_URL}/sessions/${sessionIdRef.current}/restart`, {
      method: "POST",
    }).catch(() => {});
    setCells((prev) => prev.map((c) => ({ ...c, outputs: [] })));
  }, [sessionStatus, sessionIdRef]);

  const addCell = useCallback(() => {
    setCells((prev) => [
      ...prev,
      { id: Date.now(), type: "code", content: "", outputs: [], running: false },
    ]);
  }, []);

  // -------------------------------------------------------------------------

  return (
    <div className="bg-paper text-ink text-sm antialiased min-h-screen font-mono">
      <Nav />
      <main className="max-w-content mx-auto px-8 py-16">
        {/* Notebook header */}
        <div className="group flex items-center justify-between mb-6 border-b border-rule pb-6">
          <div>
            <p className="text-[10px] tracking-widest uppercase text-muted mb-1">
              notebook · user
            </p>
            <h1 className="text-xl font-semibold tracking-tight">
              openqcd-ym1.atow
            </h1>
            <a
              href="/maintainer"
              className="opacity-0 group-hover:opacity-100 transition-opacity mt-1 inline-block text-[10px] text-muted hover:text-ink tracking-wider"
            >
              → maintainer notebook
            </a>
          </div>
          <div className="flex items-center gap-3">
            <span className="text-[10px] text-muted border border-rule px-2 py-1 rounded-sm tracking-wider">
              kernel: python 3
            </span>
            <button
              onClick={restart}
              disabled={sessionStatus !== "ready"}
              className="text-[11px] tracking-wider px-3 py-1 border border-rule rounded-sm hover:bg-paper-alt disabled:opacity-40 disabled:cursor-not-allowed transition-colors text-muted hover:text-ink"
            >
              restart
            </button>
            <button
              onClick={runAll}
              disabled={sessionStatus !== "ready"}
              className="text-[11px] tracking-wider px-3 py-1 bg-accent1 text-paper rounded-sm hover:bg-accent2 disabled:opacity-40 disabled:cursor-not-allowed transition-colors"
            >
              run all
            </button>
            <button
              onClick={() => setShowExplorer((v) => !v)}
              className={`text-[11px] tracking-wider px-3 py-1 border rounded-sm transition-colors ${
                showExplorer
                  ? "border-accent2 text-accent2"
                  : "border-rule text-muted hover:border-muted hover:text-ink"
              }`}
            >
              files
            </button>
          </div>
        </div>

        {/* Session status */}
        <div className="mb-6">
          <SessionBar
            status={sessionStatus}
            error={sessionError}
            sessionId={sessionId}
            onStop={stopSession}
            onStart={startSession}
          />
        </div>

        {/* Cells */}
        <div className="space-y-3">
          {cells.map((cell, i) => (
            <Cell
              key={cell.id}
              cell={cell}
              index={i + 1}
              isActive={activeCell === cell.id}
              onActivate={() => setActiveCell(cell.id)}
              onChange={handleChange}
              onRun={runCell}
            />
          ))}
        </div>

        {/* Add cell */}
        <button
          onClick={addCell}
          className="mt-6 w-full text-[11px] text-muted border border-dashed border-rule py-2 rounded-sm hover:border-accent1 hover:text-accent1 transition-colors tracking-wider"
        >
          + add cell
        </button>

        {/* File explorer — fixed left panel */}
        {showExplorer && (
          <div className="fixed left-0 top-12 bottom-0 w-56 z-40 flex flex-col border-r border-rule bg-paper-alt">
            <FileExplorer sessionId={sessionId} sessionStatus={sessionStatus} />
          </div>
        )}
      </main>
      <Footer />
    </div>
  );
}
